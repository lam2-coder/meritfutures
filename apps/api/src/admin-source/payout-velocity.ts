/**
 * A policy number, refused unless the corpus states it.
 *
 * `ports.ts`'s discipline made executable. An `unstated` member carries a `null`
 * and a citation to the open question, and a control that ran on one would be
 * running on a number nobody has ruled -- which is the whole of `B2`. The
 * refusal is here rather than at four call sites so a member that ever turns
 * `unstated` stops the evaluator instead of defaulting.
 */
function stated(number: PolicyNumber, name: string): bigint {
  if (number.state !== 'stated')
    throw new AdminReadError(
      `the payout-velocity policy carries \`${name}\` as UNSTATED (${number.cite}), so the alarm ` +
        'has no number to run on. ADR-201 ruling 8 makes this the one place the window lives, ' +
        'and an evaluator that supplied its own would be B2 one level down',
    );
  if (!Number.isSafeInteger(number.value) || number.value < 1)
    throw new AdminReadError(
      `the payout-velocity policy carries \`${name}\` as ${JSON.stringify(number.value)}, which ` +
        'is not a positive whole number. Money is integer cents and a threshold in basis points ' +
        'is an integer too (ADR-201 section 6)',
    );
  return BigInt(number.value);
}

