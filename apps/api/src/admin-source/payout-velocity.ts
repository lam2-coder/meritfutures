// =============================================================================
// apps/api/src/admin-source/payout-velocity.ts
// =============================================================================
// `P-M6-04`'s FOUR NUMBERS, AND THE CONTROL THEY MAKE IS ONE THAT PAGES A HUMAN.
//
// `INFRA:160` is one line -- "Over 2.5 times the 30 day average pages" -- and it
// is the reason nothing in this file may be approximately right. A liability
// figure that is wrong is read by an operator; a PAGER that is wrong wakes one,
// or fails to.
//
// -----------------------------------------------------------------------------
// THIS FILE TRANSCRIBES ADR-201 AND CHOOSES NOTHING
// -----------------------------------------------------------------------------
// `ADR-201` ruled the half `B2` was blocked on, and it is worth being precise
// about which half, because the blocker's own summary was wrong about it and the
// entry says so: the WINDOW was stated at `M06:95` all along, in words. What no
// document stated was WHAT THE AVERAGE AVERAGES, and without that the ratio is
// not a number.
//
// Ruling 2 settles it, and settles it BY PROOF rather than by preference. Of the
// three readings `avg_30d_cents` admits:
//
//   A. the 30-day TOTAL. The trailing 7 days are a SUBSET of the trailing 30, so
//      `last_7d <= total_30` on every possible history, so `ratio_bp <= 10000`,
//      so the alarm CAN NEVER FIRE, on any input, ever. That reading makes
//      `INFRA:160`'s pager a decoration and needs no data to refute.
//   B. the mean DAILY figure. A seven-day total is about seven times a daily
//      mean, so steady state sits near `70000 bp`, which is 2.8 times the
//      threshold: the pager fires on day one and every day after, and goes quiet
//      only on a roughly 64 percent COLLAPSE in payouts. The alarm would be
//      silent exactly when something is badly wrong.
//   C. the mean SCALED TO SEVEN DAYS. Steady state near `10000 bp`, reaching
//      `25000 bp` when a week's payouts run two and a half times normal.
//
// **B AND A ARE ELIMINATED AND C IS WHAT IS LEFT.** `FM-M6-07`'s words for the
// CUSUM transfer to A and B without a change: "Either constant alarms, which
// become noise, or none, which is the same as no chart." So the acceptance
// property for this module is NOT that it compiles. It is that the control
// DISCRIMINATES: silent in steady state, loud on a genuine excursion. A control
// that cannot be shown to be quiet under normal conditions is the defect
// `ADR-201` exists to prevent.
//
// -----------------------------------------------------------------------------
// EVERY NUMBER LIVES IN {@link PAYOUT_VELOCITY_POLICY} AND NOWHERE ELSE
// -----------------------------------------------------------------------------
// `ADR-201` ruling 8: the window "is carried in the implementation as ONE named,
// exported constant in ONE module, cited to this entry, and every reader imports
// it. Two literals at two sites is `B2` again, so the implementing session must
// not spell `7`, `30` or `25000` at a second site." Nothing below spells one.
//
// **AND `ELIGIBLE_HORIZON_TRADING_DAYS` IS NOT REUSED FOR THE NUMERATOR,
// WHICH IS THE TRAP THIS RULE LOOKS LIKE IT ASKS FOR.** `liability.ts` already
// exports a `7`. It is `EC-074`'s FORWARD horizon over accounts that will become
// eligible, and this one is `ADR-201`'s TRAILING window over money that has
// already left. Two independent quantities that happen to be equal today; a
// constant shared between them would move this pager's window the day `EC-074`
// moved its forecast, silently and with no ADR. `ADR-201` ruling 7 makes this
// number movable only by a superseding entry, and binding it to another
// document's number would delete exactly that property.
//
// -----------------------------------------------------------------------------
// THE DAY UNIT IS THE TRADING DAY AND THE MONEY IS ALL OF THE MONEY
// -----------------------------------------------------------------------------
// Ruling 3 counts both windows in TRADING DAYS over `trading_calendar`, and the
// argument is stationarity rather than the existence of a calendar: payout
// SUPPLY is generated by gates counted in trading days (minimum trading days,
// win days, the cadence gap), the snapshot's own clock is already the last
// closed day, and a calendar-day window would impose a THIRD clock on a quantity
// that has two. `M01:941` measures what that costs -- "Five trading days is 7
// calendar days in June and can be 9 to 10 across the year-end cluster" -- which
// on a RATIO of two windows means a genuine extraction surge inside the year-end
// cluster is MISSED and the first full week back PAGES on a calendar artifact.
//
// **THE CORPUS'S STRONGEST SOURCE AGAINST THAT IS `GLOSSARY:47`**, that whoever
// "reaches for the only calendar in the database reaches for a different set of
// days, and that substitution is wrong on roughly 104 days a year while looking
// exactly right in review". A payout SETTLES on the rail's clock: on Saturdays,
// on Thanksgiving, on days CME is shut. Ruling 4 is what keeps this module clear
// of that objection, and it is the reason {@link attributionDay} exists:
//
//   **Every settled payout is attributed to exactly one trading day: the first
//   trading day on or after the UTC date of its settlement.**
//
// The calendar is never asked whether a settlement HAPPENED. It is asked only
// WHICH SNAPSHOT FIRST SEES IT, which is `last closed day` semantics already in
// force on every other figure of this response. **No settlement is dropped and
// none is counted twice**, so the sum over 30 trading days is the sum over every
// settlement in the interval those days span. The window is bounded by trading
// days; the money inside it is all of the money.
//
// -----------------------------------------------------------------------------
// THE THIRTY-FIRST DAY IS READ, AND RULING 4 IS WHAT FORCES IT
// -----------------------------------------------------------------------------
// A settlement attributes to the OLDEST window day exactly when its date is at
// or before that day AND STRICTLY AFTER THE TRADING DAY BEFORE IT. Without that
// second bound every settlement in recorded history attributes to the oldest day
// of the window, because "the first trading day on or after" some date in 2019
// is, for a walk that can only see 30 days, the first day it can see.
//
// So this module asks the calendar for `30 + 1` days and uses the extra one as a
// BOUNDARY rather than as a term. It is a read fact and never an assumption, and
// the cost is that the control cannot evaluate until the estate holds 31 trading
// days inside one covered interval rather than 30. That is one extra day at
// launch, against an attribution rule that would otherwise be unfalsifiable.
//
// -----------------------------------------------------------------------------
// MONEY IS INTEGER CENTS AND THE RATIO INTRODUCES NO FLOAT
// -----------------------------------------------------------------------------
// Ruling 5 fixes the arithmetic and ruling 6 the empty denominator:
//
//   last_7d_cents  = sum over the 7 window days nearest the anchor
//   total_30_cents = sum over all 30
//   avg_30d_cents  = floor(total_30_cents * 7 / 30)
//   ratio_bp       = floor(last_7d_cents * 10000 / avg_30d_cents), or 0 when the
//                    denominator is 0
//   alarm          = ratio_bp > 25000
//
// **EVERY ONE OF THOSE IS COMPUTED IN `bigint` AND NOT IN `number`**, and the
// reason is stated rather than assumed. `amount_cents` is `bigint NOT NULL` in
// `0010` and a sum of it can exceed `2^53` before it exceeds the column; and
// `total_30_cents * 7` is formed BEFORE the division (ruling 5's own ordering, so
// the scaling loses at most 29 cents rather than compounding a per-day rounding
// thirty times), which multiplies the magnitude again. In `bigint` there is no
// step at which a value could be a float: `*` and `/` are integer operations and
// `/` TRUNCATES.
//
// **TRUNCATION IS `floor` HERE BECAUSE EVERY OPERAND IS NON-NEGATIVE, AND THAT IS
// A CHECK RATHER THAN A HOPE.** `0010` declares `amount_cents bigint NOT NULL
// CHECK (amount_cents > 0)`, so every summand is positive and every sum is at
// least zero; {@link centsOf} re-asserts the CHECK per row and
// {@link floorDivide} refuses a negative operand outright. Toward-zero and
// toward-negative-infinity agree on non-negative inputs and disagree by one
// everywhere else, so the guard is what makes ruling 5's word `floor` true of
// this code rather than nearly true.
//
// The two `floor`s round in OPPOSITE directions, which ruling 5 states rather
// than hides: flooring the DENOMINATOR makes it smaller and `ratio_bp` larger,
// erring toward alarming, which is the conservative direction for a control
// watching the firm's own money leave; flooring `ratio_bp` errs the other way by
// at most 1 bp against a threshold of 25000.
//
// -----------------------------------------------------------------------------
// WHAT THIS MODULE DOES NOT DO
// -----------------------------------------------------------------------------
// **IT DOES NOT COMPOSE `readLiability` AND IT DOES NOT WIDEN THE LIABILITY BOOK.** `liability.ts`'s `payout_velocity` stays in the `Omit`, and
// the reason is not that the numbers are unavailable -- they are, below -- but
// that this evaluator answers THREE WAYS and the wire carries ONE. `uncovered`
// and `exhausted` are `ADR-042` F-4's answers and `LiabilityResponse` has
// nowhere to put either: `ratio_bp` is a non-nullable `number` and `alarm` a
// non-nullable `boolean` (`API_CONTRACT:905`). Rendering an uncovered calendar as
// `0 / false` would be indistinguishable from a quiet week, which is `ADR-201`
// finding 3's gap arriving one field over and with a pager attached. Composing
// against a source that cannot fully serve the shape turns an honest 500 into a
// wrong answer, which is session 374's judgement on the same method.
//
// **IT WRITES NOTHING AND STORES NOTHING.** `ADR-201` ruling 7 refuses the window
// a column, on `0049`'s own reason for storing no `breaker_armed`, and refuses it
// a config value an operator sets, on `INV-M6-13`'s reason that "an 'extend'
// button is the one control-shaped affordance that would delete the control". A
// settable velocity window is that button on the alarm that watches the firm's
// own money leaving. {@link PayoutVelocityTx} carries `rows` and nothing else.
//
// -----------------------------------------------------------------------------
// THE COST, AND THE ONE UNBOUNDED TERM NAMED RATHER THAN HIDDEN
// -----------------------------------------------------------------------------
// `payout_transfers` IS READ WHOLE and it grows one row per transfer forever.
// `ADR-157` does admit a range term on the READ path, and `atLeast('settled_at')`
// would bound it -- but the term can only be minted by `packages/db`, and this
// directory holds NO import of that package, which is the property
// `LIABILITY_READ_TABLES`' own suite depends on. Taking the bound here is a
// change to this directory's port shape rather than a line in this function, so
// it is REPORTED and not taken, and the scan is measured in
// {@link PayoutVelocityCost} instead.
//
// **THE CALENDAR IS READ FIRST AND THE TRANSFERS ARE NOT READ AT ALL WHEN THE
// ANSWER CANNOT BE GIVEN.** An `uncovered` or `exhausted` calendar decides the
// verdict on its own, so paying an unbounded scan to reach it would buy a figure
// the verdict discards.
// =============================================================================

