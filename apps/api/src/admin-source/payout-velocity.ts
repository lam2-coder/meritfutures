function field(row: unknown, name: string, at: string): unknown {
  if (typeof row !== 'object' || row === null)
    throw new AdminReadError(
      `the accessor returned a ${typeof row} where ${at} was expected. A pager threshold ` +
        'evaluated over that would page an operator on a number nothing in the estate produced',
    );
  return (row as Record<string, unknown>)[name];
}

/**
 * `payout_transfers.amount_cents` as a `bigint`, WITH `0010`'s CHECK RE-ASSERTED.
 *
 * `bigint` AND NOT `number`, which is the opposite of `liability.ts`'s `cents`
 * and for a reason that only applies here. There the value is a single column
 * going straight onto the wire as a JSON integer. Here it is SUMMED over thirty
 * trading days and the sum is then MULTIPLIED BY SEVEN before a division, so the
 * magnitude the arithmetic reaches is not the magnitude the column holds.
 *
 * `CHECK (amount_cents > 0)` IS RE-ASSERTED RATHER THAN TRUSTED, and it is what
 * makes {@link floorDivide}'s truncation equal to ruling 5's `floor`. A single
 * negative amount would make one sum negative, and toward-zero and
 * toward-negative-infinity disagree by one cent exactly there.
 */
function centsOf(row: unknown, at: string): bigint {
  const value = field(row, 'amountCents', at);
  let asBig: bigint;
  if (typeof value === 'bigint') asBig = value;
  else if (typeof value === 'number' && Number.isSafeInteger(value)) asBig = BigInt(value);
  else if (typeof value === 'string' && /^-?\d+$/.test(value)) asBig = BigInt(value);
  else
    throw new AdminReadError(
      `${at} carries \`amount_cents\` as ${JSON.stringify(typeof value === 'bigint' ? value.toString() : value)}, ` +
        'which is not a whole number of cents. 0010 declares the column `bigint NOT NULL` and ' +
        'MERIT_BUILD_MASTER_PROMPT keeps money in integer cents with no float on the path',
    );
  if (asBig <= 0n)
    throw new AdminReadError(
      `${at} carries \`amount_cents\` as ${asBig.toString()}, and 0010 declares ` +
        '`CHECK (amount_cents > 0)`. A non-positive transfer is the database disagreeing with ' +
        'its own constraint, and it is the one input that would make ADR-201 ruling 5 word ' +
        '`floor` differ from the truncation this module computes',
    );
  return asBig;
}

/**
 * The UTC DATE of a settlement instant, which is the ONE place this module takes
 * one, and it is ruled rather than chosen.
 *
 * `liability.ts`'s `day()` REFUSES a timestamp on purpose, because "the exchange
 * trading day is a CT session and never a UTC calendar date". `ADR-201` ruling 4
 * asks for the other thing in terms: "the first trading day on or after THE UTC
 * DATE of its settlement". The two are consistent because they answer different
 * questions. A settlement's UTC date is not being treated as a trading day; it is
 * the input to a lookup whose OUTPUT is a trading day, and the lookup is the
 * whole of what keeps the rail's clock and the exchange's apart.
 */
function settlementDate(value: unknown, at: string): string {
  const ms =
    value instanceof Date
      ? value.getTime()
      : typeof value === 'string'
        ? Date.parse(value)
        : Number.NaN;
  if (!Number.isFinite(ms))
    throw new AdminReadError(
      `${at} carries \`settled_at\` as ${JSON.stringify(value)}, which is not an instant. ` +
        "0010's `payout_transfers_settled_has_timestamp` makes a settled transfer carry one, so " +
        'this is the transcription disagreeing with the database rather than a row to fold',
    );
  return new Date(ms).toISOString().slice(0, 10);
}

/**
 * Integer division that FLOORS, with the sign guard ruling 5 depends on.
 *
 * `bigint` `/` truncates toward zero. `ADR-201` section 6 says `floor`. The two
 * agree on non-negative operands and differ by one everywhere else, so rather
 * than write a branch nothing can reach, the non-negativity is asserted: every
 * summand is `> 0` by `0010`'s CHECK, {@link centsOf} re-asserts it per row, and
 * a negative reaching here means one of those failed.
 */
function floorDivide(numerator: bigint, denominator: bigint, at: string): bigint {
  if (numerator < 0n || denominator <= 0n)
    throw new AdminReadError(
      `${at} divided ${numerator.toString()} by ${denominator.toString()}. ADR-201 section 6 ` +
        'says `floor` and bigint division TRUNCATES, and the two agree only while both operands ' +
        'are non-negative. 0010 CHECKs `amount_cents > 0`, so this is a sum that could not have ' +
        'come from the settled transfers it claims to',
    );
  return numerator / denominator;
}

/** A `bigint` cents figure as the contract's JSON integer, or a refusal. */
function onWire(value: bigint, at: string): number {
  const asNumber = Number(value);
  if (!Number.isSafeInteger(asNumber))
    throw new AdminReadError(
      `${at} is ${value.toString()}, which is past the safe integer range. API_CONTRACT section ` +
        '1 types every `_cents` member a JSON integer, and a rounded one is wrong where it is ' +
        'hardest to notice',
    );
  return asNumber;
}

