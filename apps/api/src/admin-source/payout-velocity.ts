/**
 * The first window day at or after a settlement date, or which side it fell.
 *
 * THE WINDOW DAYS ARE CONSECUTIVE TRADING DAYS AND THAT IS WHAT MAKES A SCAN
 * CORRECT. {@link readTradingLookback} takes every non-holiday row inside one
 * covered interval and slices the newest `span`, so no session is skipped
 * between two neighbours: the first entry at or after a date IS the first
 * trading day at or after it, with no third table consulted.
 *
 * `boundary` IS THE TRADING DAY BEFORE THE WINDOW and it is the whole reason a
 * settlement from 2019 does not land on the window's oldest day. A date at or
 * before it attributed to a day this walk cannot see.
 */
function attributionDay(
  date: string,
  boundary: string,
  windowDays: readonly string[],
  anchorDay: string,
): { readonly where: 'before' } | { readonly where: 'after' } | { readonly day: string } {
  if (date > anchorDay) return { where: 'after' };
  if (date <= boundary) return { where: 'before' };
  for (const day of windowDays) if (day >= date) return { day };
  // UNREACHABLE, AND IT IS ASSERTED RATHER THAN ASSUMED. `date <= anchorDay` and
  // the anchor is the last window day, so the loop above always returns. A throw
  // here would mean the window came back without its own anchor in it.
  throw new AdminReadError(
    `a settlement dated ${date} is at or before the anchor ${anchorDay} and after the boundary ` +
      `${boundary}, and no day of the window is at or after it. The window is ` +
      `${String(windowDays.length)} consecutive trading days ending at the anchor, so this is ` +
      'the walk returning a window that does not contain its own anchor',
  );
}

// -----------------------------------------------------------------------------
// The evaluation
// -----------------------------------------------------------------------------

/**
 * `P-M6-04`'s four numbers as of an instant, or the reason there are none.
 *
 * `ADR-201` rulings 1 through 6 transcribed, and every number taken from
 * {@link PAYOUT_VELOCITY_POLICY} rather than spelled here (ruling 8).
 *
 * THE ORDER OF THE TWO READS IS PART OF THE DESIGN. The calendar decides whether
 * a verdict is possible at all, and `payout_transfers` is the unbounded scan, so
 * an `uncovered` or `exhausted` calendar returns before a single transfer row is
 * read and says so in {@link PayoutVelocityCost} with a `transferRowsScanned` of
 * zero.
 */
export async function evaluatePayoutVelocity(
  tx: PayoutVelocityTx,
  asOf: string,
): Promise<PayoutVelocityResult> {
  const numeratorDays = stated(PAYOUT_VELOCITY_POLICY.numeratorTradingDays, 'numeratorTradingDays');
  const denominatorDays = stated(
    PAYOUT_VELOCITY_POLICY.denominatorTradingDays,
    'denominatorTradingDays',
  );
  const thresholdBp = stated(PAYOUT_VELOCITY_POLICY.thresholdBp, 'thresholdBp');
  const bpScale = stated(PAYOUT_VELOCITY_POLICY.basisPointScale, 'basisPointScale');

  if (numeratorDays > denominatorDays)
    throw new AdminReadError(
      `the payout-velocity policy makes the numerator window ${numeratorDays.toString()} trading ` +
        `days and the denominator ${denominatorDays.toString()}. ADR-201 ruling 2's proof that ` +
        'the 30-day TOTAL cannot be the reading rests on the numerator window being a SUBSET of ' +
        'the denominator window, and a numerator longer than its own denominator is not one',
    );

  // THE THIRTY-FIRST DAY IS THE ATTRIBUTION BOUNDARY AND NOT A TERM OF THE
  // WINDOW. The header states why ruling 4 forces it to be read rather than
  // assumed.
  const span = Number(denominatorDays) + 1;
  const { lookback, cost: calendarCost } = await readTradingLookback(tx, asOf, span);

  const emptyTransferCost = {
    transferRowsScanned: 0,
    settledTransfersRead: 0,
    settledInstantsOnUnsettledRows: 0,
    settlementsAttributedInWindow: 0,
    settlementsBeforeWindow: 0,
    settlementsAfterAnchor: 0,
    ...calendarCost,
  } as const;

  if (lookback.kind === 'uncovered')
    return {
      verdict: { kind: 'uncovered', anchor_day: lookback.anchor_day, detail: lookback.detail },
      cost: emptyTransferCost,
    };

  if (lookback.kind === 'exhausted')
    return {
      verdict: {
        kind: 'exhausted',
        anchor_day: lookback.anchor_day,
        trading_days_found: lookback.days.length,
        short_by: lookback.short_by,
        detail:
          `${lookback.detail}. ADR-201 section 7 answers an EMPTY DENOMINATOR and cannot answer ` +
          'an ABSENT WINDOW: a thirty-day total scaled by 7/30 when the calendar held fewer than ' +
          'thirty days is a denominator smaller than the one four documents describe, and a ' +
          'smaller denominator is a larger ratio against a threshold that pages',
      },
      cost: emptyTransferCost,
    };

  const walked = lookback.days.map((entry) => entry.trading_day);
  const boundaryDay = walked[0];
  const windowDays = walked.slice(1);
  const anchorDay = lookback.anchor_day;
  if (boundaryDay === undefined || windowDays.length !== Number(denominatorDays))
    throw new AdminReadError(
      `the trailing walk resolved ${String(walked.length)} trading days where ` +
        `${String(span)} were asked for. A resolved lookback returns exactly its span, so this ` +
        'is the walk disagreeing with its own verdict',
    );

  const numeratorFromDay = windowDays[windowDays.length - Number(numeratorDays)];
  const denominatorFromDay = windowDays[0];
  if (numeratorFromDay === undefined || denominatorFromDay === undefined)
    throw new AdminReadError(
      'the trailing walk resolved a window with no first day, which a window of ' +
        `${String(denominatorDays)} consecutive trading days cannot be`,
    );

  // THE UNBOUNDED SCAN, PAID ONLY NOW THAT A VERDICT IS POSSIBLE.
  const transferRows = await tx.rows('payoutTransfers');

  const attributed = new Map<string, bigint>();
  for (const day of windowDays) attributed.set(day, 0n);

  let settledTransfersRead = 0;
  let settledInstantsOnUnsettledRows = 0;
  let inWindow = 0;
  let before = 0;
  let after = 0;

  for (const row of transferRows) {
    const at = 'a payout transfer row';
    const status = field(row, 'status', at);
    if (typeof status !== 'string' || status === '')
      throw new AdminReadError(
        `${at} carries no \`status\`, and 0010 declares the column \`text NOT NULL\` with a ` +
          'CHECK over five rail states. A transfer whose state is unreadable is money this ' +
          'evaluator can neither count nor safely ignore',
      );

    const settledAt = field(row, 'settledAt', at);
    const hasInstant = settledAt !== null && settledAt !== undefined;

    // **THE `CHECK` IS ONE-DIRECTIONAL AND THE SELECTION IS ON `status`.**
    // `payout_transfers_settled_has_timestamp` is
    // `CHECK (status <> 'settled' OR settled_at IS NOT NULL)`, which forbids a
    // settled row with no instant and PERMITS a failed or retrying row that
    // carries one. So selecting on `settled_at IS NOT NULL` would count a
    // transfer the rail did not settle as money that left, which overstates the
    // numerator of an alarm. Selecting on `status` is safe in the other
    // direction because the CHECK guarantees the instant is there.
    if (status !== 'settled') {
      if (hasInstant) settledInstantsOnUnsettledRows += 1;
      continue;
    }
    if (!hasInstant)
      throw new AdminReadError(
        `${at} carries \`status = 'settled'\` and no \`settled_at\`, which ` +
          "0010's `payout_transfers_settled_has_timestamp` forbids outright. That is the " +
          'database disagreeing with its own CHECK rather than a row to attribute',
      );

    settledTransfersRead += 1;
    const date = settlementDate(settledAt, at);
    const cents = centsOf(row, at);
    const landed = attributionDay(date, boundaryDay, windowDays, anchorDay);
    if ('where' in landed) {
      if (landed.where === 'before') before += 1;
      else after += 1;
      continue;
    }
    inWindow += 1;
    attributed.set(landed.day, (attributed.get(landed.day) ?? 0n) + cents);
  }

  let total30 = 0n;
  let last7 = 0n;
  for (const day of windowDays) {
    const cents = attributed.get(day) ?? 0n;
    total30 += cents;
    if (day >= numeratorFromDay) last7 += cents;
  }

  // RULING 5, IN THE ORDER IT WRITES IT. `total_30_cents * 7` is formed before
  // the division, so the scaling loses at most 29 cents rather than compounding a
  // per-day rounding thirty times.
  const avg30 = floorDivide(total30 * numeratorDays, denominatorDays, 'avg_30d_cents');

  // RULING 6. A velocity alarm is a RELATIVE control and a firm with no payout
  // history has nothing to be relative to; firing on an empty denominator is
  // `AS-M6-02`'s self-inflicted outage with a pager instead of a sales pause.
  const ratioBp = avg30 === 0n ? 0n : floorDivide(last7 * bpScale, avg30, 'ratio_bp');

  return {
    verdict: {
      kind: 'evaluated',
      anchor_day: anchorDay,
      numerator_from_day: numeratorFromDay,
      denominator_from_day: denominatorFromDay,
      attribution_boundary_day: boundaryDay,
      total_30_cents: onWire(total30, 'the trailing 30 trading day settled total'),
      panel: {
        last_7d_cents: onWire(last7, 'last_7d_cents'),
        avg_30d_cents: onWire(avg30, 'avg_30d_cents'),
        ratio_bp: onWire(ratioBp, 'ratio_bp'),
        // RULING 1, STRICT. Four documents say "above", "over" or ">", and not
        // one says "at or above", so exactly 25000 does not page.
        alarm: ratioBp > thresholdBp,
      },
    },
    cost: {
      transferRowsScanned: transferRows.length,
      settledTransfersRead,
      settledInstantsOnUnsettledRows,
      settlementsAttributedInWindow: inWindow,
      settlementsBeforeWindow: before,
      settlementsAfterAnchor: after,
      ...calendarCost,
    },
  };
}
